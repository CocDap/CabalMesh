//! Primitives for restoring onto a **new** device, and for the owner's
//! authenticated messages to its guardians (backup refresh, restore veto).
//!
//! # Why everyday unlock is not enough
//!
//! Everyday unlock ([`crate::protocol::UnlockRequest`]) only works on the
//! device that enrolled: it needs the owner's recovery key to compute tags
//! and open replies, and the encrypted vault the reconstructed key opens.
//! A lost device takes all three with it. Restore therefore needs:
//!
//! 1. Something the *person* carries, so a brand-new device can find its
//!    guardians: the [`RestoreSecret`], shown once as a short code. It is
//!    not a key — without K guardian approvals it opens nothing — but it is
//!    what lets a request be recognised ([`restore_tag`]) and what wraps the
//!    vault backup guardians hold ([`backup_key`]), so a single guardian
//!    holding that backup cannot brute-force a weak passphrase offline.
//! 2. A copy of the vault's contents held by guardians, wrapped under a key
//!    only K shares *and* the restore code together produce.
//!
//! # Owner authentication
//!
//! Backup refreshes and restore cancels must come from the original device,
//! not from whoever typed the restore code. They are authenticated with
//! [`mac`] under an `owner_auth_key` handed to guardians at enrollment and
//! kept only on the owner's device — never part of the restore code.

use cabal_vault::DataKey;
use chacha20poly1305::aead::{Aead, KeyInit, Payload};
use chacha20poly1305::{ChaCha20Poly1305, Nonce};
use hmac::{Hmac, Mac};
use rand_core::{OsRng, RngCore};
use sha2::{Digest, Sha256};
use zeroize::{Zeroize, ZeroizeOnDrop};

use crate::protocol::TAG_LEN;

const NONCE_LEN: usize = 12;
/// Crockford base32: no I, L, O or U, so a hand-copied code survives the
/// usual misreadings.
const ALPHABET: &[u8; 32] = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum RestoreError {
    #[error("that restore code is not valid — check for a mistyped character")]
    BadCode,
    #[error("decryption failed")]
    Decrypt,
}

/// The secret behind the restore code. Generated by the owner at
/// enrollment, shown to the person, never sent to anyone in the clear.
#[derive(Clone, Zeroize, ZeroizeOnDrop, PartialEq, Eq)]
pub struct RestoreSecret([u8; 32]);

impl std::fmt::Debug for RestoreSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("RestoreSecret(..)")
    }
}

impl RestoreSecret {
    #[must_use]
    pub fn generate() -> Self {
        let mut bytes = [0_u8; 32];
        OsRng.fill_bytes(&mut bytes);
        Self(bytes)
    }

    #[must_use]
    pub const fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    #[must_use]
    pub const fn to_bytes(&self) -> [u8; 32] {
        self.0
    }

    /// The code shown to the person: 32 bytes plus a one-byte checksum, in
    /// Crockford base32, grouped in fours (`XXXX-XXXX-…`, 53 characters).
    #[must_use]
    pub fn to_code(&self) -> String {
        let mut data = self.0.to_vec();
        data.push(checksum(&self.0));
        let encoded = base32_encode(&data);
        encoded
            .as_bytes()
            .chunks(4)
            .map(|c| std::str::from_utf8(c).expect("ascii"))
            .collect::<Vec<_>>()
            .join("-")
    }

    /// Parses a code typed back in. Case, separators and whitespace are
    /// ignored; `I`/`L` read as `1` and `O` as `0`.
    ///
    /// # Errors
    ///
    /// [`RestoreError::BadCode`] if it does not decode or the checksum fails.
    pub fn from_code(code: &str) -> Result<Self, RestoreError> {
        let cleaned: String = code
            .chars()
            .filter(|c| !c.is_whitespace() && *c != '-')
            .map(|c| match c.to_ascii_uppercase() {
                'I' | 'L' => '1',
                'O' => '0',
                other => other,
            })
            .collect();
        let bytes = base32_decode(&cleaned).ok_or(RestoreError::BadCode)?;
        if bytes.len() != 33 {
            return Err(RestoreError::BadCode);
        }
        let mut secret = [0_u8; 32];
        secret.copy_from_slice(&bytes[..32]);
        if checksum(&secret) != bytes[32] {
            return Err(RestoreError::BadCode);
        }
        Ok(Self(secret))
    }

    /// What guardians store to recognise a restore request. One-way: holding
    /// it does not reveal the code, so a guardian cannot unwrap the backup.
    #[must_use]
    pub fn lookup(&self) -> [u8; 32] {
        hash(b"cabalmesh/restore-lookup/v1", &[&self.0])
    }

    /// The key the guardian-held vault backup is wrapped under. Needs both
    /// the reconstructed recovery key and this secret.
    #[must_use]
    pub fn backup_key(&self, recovery_key: &DataKey) -> [u8; 32] {
        hash(b"cabalmesh/restore-backup/v1", &[&recovery_key.expose_for_storage(), &self.0])
    }
}

/// The tag a new device broadcasts in a restore request: recognisable only
/// by a holder of `lookup`, and different under every nonce.
#[must_use]
pub fn restore_tag(lookup: &[u8; 32], nonce: &[u8; TAG_LEN]) -> [u8; TAG_LEN] {
    truncate(hash(b"cabalmesh/restore-tag/v1", &[lookup, nonce]))
}

/// The tag a guardian broadcasts while a restore for this owner is pending,
/// so the original device — and nobody else — can notice and veto.
#[must_use]
pub fn pending_tag(owner_auth_key: &[u8; 32], nonce: &[u8; TAG_LEN]) -> [u8; TAG_LEN] {
    truncate(hash(b"cabalmesh/restore-pending/v1", &[owner_auth_key, nonce]))
}

/// HMAC-SHA256 over `parts`, domain-separated by `domain`. Each part is
/// length-prefixed so `["ab","c"]` and `["a","bc"]` never collide.
#[must_use]
pub fn mac(owner_auth_key: &[u8; 32], domain: &[u8], parts: &[&[u8]]) -> [u8; 32] {
    let mut m = <Hmac<Sha256> as Mac>::new_from_slice(owner_auth_key).expect("HMAC takes any key length");
    feed(&mut m, domain, parts);
    m.finalize().into_bytes().into()
}

/// Constant-time check of a [`mac`].
#[must_use]
pub fn verify_mac(owner_auth_key: &[u8; 32], domain: &[u8], parts: &[&[u8]], tag: &[u8; 32]) -> bool {
    let mut m = <Hmac<Sha256> as Mac>::new_from_slice(owner_auth_key).expect("HMAC takes any key length");
    feed(&mut m, domain, parts);
    m.verify_slice(tag).is_ok()
}

/// A fresh random 32-byte value, for `owner_auth_key`.
#[must_use]
pub fn random_key() -> [u8; 32] {
    let mut bytes = [0_u8; 32];
    OsRng.fill_bytes(&mut bytes);
    bytes
}

/// ChaCha20-Poly1305 with a random nonce, output `nonce ‖ ciphertext`.
#[must_use]
pub fn aead_seal(key: &[u8; 32], aad: &[u8], plaintext: &[u8]) -> Vec<u8> {
    let cipher = ChaCha20Poly1305::new(key.into());
    let mut nonce = [0_u8; NONCE_LEN];
    OsRng.fill_bytes(&mut nonce);
    let ciphertext = cipher
        .encrypt(Nonce::from_slice(&nonce), Payload { msg: plaintext, aad })
        .expect("chacha20poly1305 encryption should not fail for vault-sized payloads");
    let mut out = nonce.to_vec();
    out.extend(ciphertext);
    out
}

/// Opens [`aead_seal`]'s output.
///
/// # Errors
///
/// [`RestoreError::Decrypt`] on a wrong key, wrong `aad`, or tampering.
pub fn aead_open(key: &[u8; 32], aad: &[u8], sealed: &[u8]) -> Result<Vec<u8>, RestoreError> {
    if sealed.len() < NONCE_LEN {
        return Err(RestoreError::Decrypt);
    }
    let (nonce, ciphertext) = sealed.split_at(NONCE_LEN);
    ChaCha20Poly1305::new(key.into())
        .decrypt(Nonce::from_slice(nonce), Payload { msg: ciphertext, aad })
        .map_err(|_| RestoreError::Decrypt)
}

fn feed(m: &mut Hmac<Sha256>, domain: &[u8], parts: &[&[u8]]) {
    m.update(&(domain.len() as u64).to_be_bytes());
    m.update(domain);
    for part in parts {
        m.update(&(part.len() as u64).to_be_bytes());
        m.update(part);
    }
}

fn hash(domain: &[u8], parts: &[&[u8]]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update((domain.len() as u64).to_be_bytes());
    hasher.update(domain);
    for part in parts {
        hasher.update((part.len() as u64).to_be_bytes());
        hasher.update(part);
    }
    hasher.finalize().into()
}

fn truncate(digest: [u8; 32]) -> [u8; TAG_LEN] {
    let mut tag = [0_u8; TAG_LEN];
    tag.copy_from_slice(&digest[..TAG_LEN]);
    tag
}

fn checksum(secret: &[u8; 32]) -> u8 {
    hash(b"cabalmesh/restore-code-check/v1", &[secret])[0]
}

fn base32_encode(data: &[u8]) -> String {
    let mut out = String::new();
    let mut buffer: u32 = 0;
    let mut bits = 0;
    for &byte in data {
        buffer = (buffer << 8) | u32::from(byte);
        bits += 8;
        while bits >= 5 {
            bits -= 5;
            out.push(ALPHABET[((buffer >> bits) & 31) as usize] as char);
        }
    }
    if bits > 0 {
        out.push(ALPHABET[((buffer << (5 - bits)) & 31) as usize] as char);
    }
    out
}

fn base32_decode(text: &str) -> Option<Vec<u8>> {
    let mut out = Vec::new();
    let mut buffer: u32 = 0;
    let mut bits = 0;
    for c in text.bytes() {
        let value = ALPHABET.iter().position(|&a| a == c)? as u32;
        buffer = (buffer << 5) | value;
        bits += 5;
        if bits >= 8 {
            bits -= 8;
            out.push(((buffer >> bits) & 0xff) as u8);
        }
    }
    // Leftover bits must be zero padding, or the code was mistyped.
    if bits >= 5 || (buffer & ((1 << bits) - 1)) != 0 {
        return None;
    }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_code_round_trips_and_tolerates_how_people_type() {
        let secret = RestoreSecret::generate();
        let code = secret.to_code();
        assert_eq!(code.len(), 53 + 13, "53 characters in groups of four");
        assert_eq!(RestoreSecret::from_code(&code).unwrap(), secret);

        let sloppy = code.to_lowercase().replace('-', " ").replace('1', "l").replace('0', "o");
        assert_eq!(RestoreSecret::from_code(&sloppy).unwrap(), secret);
    }

    #[test]
    fn a_single_mistyped_character_is_caught() {
        let code = RestoreSecret::generate().to_code();
        let mut chars: Vec<char> = code.chars().collect();
        chars[5] = if chars[5] == 'A' { 'B' } else { 'A' };
        let typo: String = chars.into_iter().collect();
        assert_eq!(RestoreSecret::from_code(&typo), Err(RestoreError::BadCode));
    }

    #[test]
    fn tags_are_unlinkable_across_nonces_and_bound_to_the_secret() {
        let a = RestoreSecret::generate().lookup();
        let b = RestoreSecret::generate().lookup();
        assert_ne!(restore_tag(&a, &[1; TAG_LEN]), restore_tag(&a, &[2; TAG_LEN]));
        assert_ne!(restore_tag(&a, &[1; TAG_LEN]), restore_tag(&b, &[1; TAG_LEN]));
        assert_eq!(restore_tag(&a, &[1; TAG_LEN]), restore_tag(&a, &[1; TAG_LEN]));
    }

    #[test]
    fn the_backup_key_needs_both_the_recovery_key_and_the_code() {
        let secret = RestoreSecret::generate();
        let rk = DataKey::from_bytes([1; 32]);
        let sealed = aead_seal(&secret.backup_key(&rk), b"aad", b"vault");
        assert_eq!(aead_open(&secret.backup_key(&rk), b"aad", &sealed).unwrap(), b"vault");
        assert!(aead_open(&secret.backup_key(&DataKey::from_bytes([2; 32])), b"aad", &sealed).is_err());
        assert!(aead_open(&RestoreSecret::generate().backup_key(&rk), b"aad", &sealed).is_err());
        assert!(aead_open(&secret.backup_key(&rk), b"other", &sealed).is_err());
    }

    #[test]
    fn macs_verify_only_under_the_same_key_domain_and_parts() {
        let key = random_key();
        let tag = mac(&key, b"cancel", &[b"ab", b"c"]);
        assert!(verify_mac(&key, b"cancel", &[b"ab", b"c"], &tag));
        assert!(!verify_mac(&key, b"cancel", &[b"a", b"bc"], &tag));
        assert!(!verify_mac(&key, b"backup", &[b"ab", b"c"], &tag));
        assert!(!verify_mac(&random_key(), b"cancel", &[b"ab", b"c"], &tag));
    }
}
